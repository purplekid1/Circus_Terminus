#!/usr/bin/env bash
# Writes Scenes/car.tscn -- the car that pulls up at the gate in the intro.
#
# The body is one CSGCombiner3D (one draw call for ninety brushes, evaluated
# once at load). Hung off it are the things that have to be nodes rather than
# geometry: two headlamp beams, two tail glows, and a dust trail behind the
# rear wheels. Scripts/CarArrival.gd drives the whole thing.

set -euo pipefail
cd "$(dirname "$0")/.."
# RETIRED, AND IT REFUSES TO RUN.
#
# The car is a hand-modelled FBX now -- Models/car/Car.fbx -- and Scenes/car.tscn
# is hand-edited around it: the model instance, its per-mesh materials, and four
# lamps and a dust trail placed against the MODEL rather than against the
# brushwork below. Running this would write all of that away and put the fifty
# CSG boxes back.
#
# It is kept, rather than deleted, because it is the only record of what the old
# car measured -- 5.10 x 2.14 x 2.05, nose at z -2.55 -- which is what the new
# one was scaled to match. Delete the guard if the model is ever dropped.
if [ "${GEN_CAR_I_MEAN_IT:-}" != "yes" ]; then
  echo "tools/gen_car.sh is retired: Scenes/car.tscn is hand-edited around" >&2
  echo "Models/car/Car.fbx. Running this would overwrite the model, its" >&2
  echo "materials and the lamp placement with the old CSG body." >&2
  echo "Set GEN_CAR_I_MEAN_IT=yes if you really want the brushwork back." >&2
  exit 1
fi


AWK=${AWK:-awk}
BODY=$(mktemp)
trap 'rm -f "$BODY"' EXIT

# IPARENT=Body, or the brushes land on the scene root and the Body combiner
# comes out empty -- see the note on IPAR() in tools/items.awk.
"$AWK" -v IPARENT=Body -f tools/lib.awk -f tools/items.awk -f tools/car.awk \
  -e 'BEGIN { c_car() }' > "$BODY"

mats=$(grep -o 'ExtResource("Mat_[A-Za-z0-9_]*")' "$BODY" \
       | sed 's/ExtResource("//;s/")//' | sort -u)

{
  echo "[gd_scene load_steps=20 format=3 uid=\"uid://ccarintro001\"]"
  echo
  echo "; THE CAR. Body generated by tools/gen_car.sh -- do not hand-edit the"
  echo "; Body node's children. Lamps, beams and the dust trail are hand-added"
  echo "; below the generated block and are preserved by the generator only"
  echo "; because they live in this heredoc, so edit them HERE."
  echo
  echo '[ext_resource type="Script" path="res://Scripts/CarArrival.gd" id="1_car"]'
  for m in $mats; do
    echo "[ext_resource type=\"Material\" path=\"res://Materials/$m.tres\" id=\"$m\"]"
  done
  cat <<'HEAD'

[sub_resource type="Gradient" id="Grad_dust"]
offsets = PackedFloat32Array(0, 0.25, 1)
colors = PackedColorArray(0.5, 0.47, 0.42, 0, 0.45, 0.42, 0.37, 0.5, 0.35, 0.33, 0.3, 0)

[sub_resource type="GradientTexture1D" id="Tex_dust"]
gradient = SubResource("Grad_dust")

[sub_resource type="StandardMaterial3D" id="Mat_dustmote"]
transparency = 1
shading_mode = 0
vertex_color_use_as_albedo = true
albedo_color = Color(0.5, 0.48, 0.44, 1)
billboard_mode = 3
billboard_keep_scale = true
disable_receive_shadows = true

[sub_resource type="QuadMesh" id="Mesh_dustmote"]
material = SubResource("Mat_dustmote")
size = Vector2(0.55, 0.55)

[sub_resource type="ParticleProcessMaterial" id="Proc_dust"]
lifetime_randomness = 0.6
emission_shape = 3
emission_box_extents = Vector3(0.9, 0.05, 0.3)
direction = Vector3(0, 0.4, 1)
spread = 40.0
initial_velocity_min = 0.4
initial_velocity_max = 1.8
gravity = Vector3(0, 0.12, 0)
damping_min = 0.6
damping_max = 1.6
scale_min = 0.6
scale_max = 2.6
color_ramp = SubResource("Tex_dust")
turbulence_enabled = true
turbulence_noise_strength = 0.5
turbulence_noise_scale = 1.6

[node name="Car" type="Node3D"]
script = ExtResource("1_car")

[node name="Body" type="CSGCombiner3D" parent="."]
HEAD
  cat "$BODY"
  cat <<'TAIL'

[node name="HeadBeamL" type="SpotLight3D" parent="."]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, -0.62, 0.86, -2.6)
light_color = Color(1, 0.95, 0.85, 1)
light_energy = 9.0
light_volumetric_fog_energy = 3.0
shadow_enabled = true
shadow_bias = 0.05
spot_range = 42.0
spot_attenuation = 1.1
spot_angle = 31.0
spot_angle_attenuation = 0.7

[node name="HeadBeamR" type="SpotLight3D" parent="."]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0.62, 0.86, -2.6)
light_color = Color(1, 0.95, 0.85, 1)
light_energy = 9.0
light_volumetric_fog_energy = 3.0
shadow_enabled = false
spot_range = 42.0
spot_attenuation = 1.1
spot_angle = 31.0
spot_angle_attenuation = 0.7

[node name="TailGlow" type="OmniLight3D" parent="."]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0.8, 2.55)
light_color = Color(1, 0.16, 0.1, 1)
light_energy = 1.4
omni_range = 3.4
omni_attenuation = 2.0

[node name="CabinGlow" type="OmniLight3D" parent="."]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 1.2, 0.4)
light_color = Color(1, 0.86, 0.6, 1)
light_energy = 0.0
omni_range = 2.6
omni_attenuation = 2.4

[node name="Dust" type="GPUParticles3D" parent="."]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0.12, 1.9)
emitting = false
amount = 60
lifetime = 2.4
randomness = 1.0
visibility_aabb = AABB(-6, -1, -6, 12, 6, 12)
local_coords = false
process_material = SubResource("Proc_dust")
draw_pass_1 = SubResource("Mesh_dustmote")
TAIL
} > Scenes/car.tscn

printf 'wrote Scenes/car.tscn (%s nodes)\n' "$(grep -c '^\[node' Scenes/car.tscn)"
