#!/usr/bin/env bash
# Writes Scenes/storm_door.tscn -- the cellar doors in the ground outside the
# house, and the stone and timber they sit in.
#
# It was one flat 3x4 metre box with a brown material on it. Now it is a pair
# of ledged-and-braced leaves with strap hinges, pull rings and a broken
# padlock, in a stone coping.
#
# THE PLACEMENT TRANSFORM IS FIXED. mansion.tscn is hand-arranged and cannot
# be regenerated, and it places this scene with a basis that maps local
# (x,y,z) to world (y,z,x) -- which is what lays the doors flat. So the local
# frame here is not negotiable: see the header of tools/stormdoor.awk.
#
# The root's script changes from Door.gd to StormDoors.gd, which drives two
# hinges instead of one. That is safe for the instance in mansion.tscn: its
# only override is `examine_lines`, which both scripts inherit from
# Interactable.

set -euo pipefail
cd "$(dirname "$0")/.."

AWK=${AWK:-awk}
BODY=$(mktemp)
trap 'rm -f "$BODY"' EXIT

# Each leaf in its own hinge space, plus the static frame. The east leaf is
# the same code with dir = -1, so the two cannot drift apart.
"$AWK" -f tools/lib.awk -f tools/items.awk -f tools/stormdoor.awk -e '
BEGIN {
  printf "\n[node name=\"Frame\" type=\"CSGCombiner3D\" parent=\".\"]\n"
  printf "use_collision = true\n"
  sd_frame("Frame")

  printf "\n[node name=\"HingeWest\" type=\"Node3D\" parent=\".\"]\n"
  printf "\n[node name=\"Panel\" type=\"AnimatableBody3D\" parent=\"HingeWest\"]\n"
  printf "sync_to_physics = false\n"
  printf "\n[node name=\"CollisionShape3D\" type=\"CollisionShape3D\" parent=\"HingeWest/Panel\"]\n"
  printf "transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0.75, 0, 0)\n"
  printf "shape = SubResource(\"Shape_leaf\")\n"
  printf "\n[node name=\"Leaf\" type=\"CSGCombiner3D\" parent=\"HingeWest/Panel\"]\n"
  sd_leaf("HingeWest/Panel/Leaf", 1)

  printf "\n[node name=\"HingeEast\" type=\"Node3D\" parent=\".\"]\n"
  printf "transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, %.4f, 0, 0)\n", SD_SPAN()
  printf "\n[node name=\"Panel\" type=\"AnimatableBody3D\" parent=\"HingeEast\"]\n"
  printf "sync_to_physics = false\n"
  printf "\n[node name=\"CollisionShape3D\" type=\"CollisionShape3D\" parent=\"HingeEast/Panel\"]\n"
  printf "transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, -0.75, 0, 0)\n"
  printf "shape = SubResource(\"Shape_leaf\")\n"
  printf "\n[node name=\"Leaf\" type=\"CSGCombiner3D\" parent=\"HingeEast/Panel\"]\n"
  sd_leaf("HingeEast/Panel/Leaf", -1)
}' > "$BODY"

mats=$(grep -o 'ExtResource("Mat_[A-Za-z0-9_]*")' "$BODY" \
       | sed 's/ExtResource("//;s/")//' | sort -u)

{
  echo '[gd_scene load_steps=12 format=3]'
  echo
  echo '; THE CELLAR DOORS. Generated by tools/gen_stormdoor.sh.'
  echo ';'
  echo '; Two leaves on two hinges, driven as one door by StormDoors.gd. The'
  echo '; local frame is dictated by the placement transform in mansion.tscn --'
  echo '; read tools/stormdoor.awk before moving anything.'
  echo
  echo '[ext_resource type="Script" path="res://Scripts/StormDoors.gd" id="1_storm"]'
  for m in $mats; do
    echo "[ext_resource type=\"Material\" path=\"res://Materials/$m.tres\" id=\"$m\"]"
  done
  echo
  echo '; One box per leaf. A trimesh of fifteen boards would let the player'
  echo '; fall between them, and a hatch is a plank as far as physics goes.'
  echo '[sub_resource type="BoxShape3D" id="Shape_leaf"]'
  echo 'size = Vector3(1.5, 4.2, 0.16)'
  echo
  echo '[node name="StormDoor" type="Node3D" groups=["interactable"]]'
  echo 'script = ExtResource("1_storm")'
  echo 'prompt = "Storm doors"'
  echo 'open_angle = 104.0'
  echo 'swing_time = 1.3'
  echo 'first_open_time = 2.4'
  cat "$BODY"
} > Scenes/storm_door.tscn

printf 'wrote Scenes/storm_door.tscn (%s nodes)\n' "$(grep -c '^\[node' Scenes/storm_door.tscn)"
