#!/usr/bin/env bash
# Writes Scenes/steps_porch.tscn and Scenes/steps_cellar.tscn -- the two
# flights of steps OUTSIDE the house.
#
# Both are instanced by Scenes/mansion.tscn, so every coordinate below is in
# MANSION-LOCAL space. The mansion sits at world (0, 0.35, -41.5), which means:
#
#   local y  0.00  = the porch deck and the ground floor   (world  0.35)
#   local y -0.30  = the lawn                              (world  0.05)
#   local y -3.60  = the cellar pit floor                  (world -3.25)
#   local z  4.00  = the front edge of the porch deck      (world -37.50)
#
# WHY THESE EXIST
#
# The porch deck stands 30 cm above the lawn, all the way along a forty metre
# frontage, and the player has no step-up. Walking at the house across the
# grass you hit an invisible wall; the only way up was the paved path, which
# ran flush into the deck and so did not read as a way up at all. Hence a
# proper stoop: three bluestone treads between two brick cheeks, with the path
# now dipping to meet it (see WalkRamp in demo_level.tscn).
#
# The cellar flight is the opposite problem. The pit below the storm doors
# already had a ramp collider -- CellarPit/Ramp, in the mansion scene -- and
# NOTHING TO SEE. You opened the doors and walked down a smooth invisible
# slope into the dark. The steps here are laid on exactly the endpoints that
# ramp was built from, so they sit under its surface rather than tripping the
# player on every tread.

set -euo pipefail
cd "$(dirname "$0")/.."

AWK=${AWK:-awk}

# The awk pass prints the nodes, then a sentinel, then one BoxShape3D per
# ramp. One pass, split here, rather than running awk twice and hoping the two
# runs agree about how big the collider is.
SENTINEL='#---subresources---'

emit() { # out-scene root-name awk-body
  local out=$1 root=$2 body_src=$3
  local all body subs mats steps
  all=$(mktemp); body=$(mktemp); subs=$(mktemp)

  "$AWK" -f tools/lib.awk -f tools/steps.awk -e "$body_src" \
    -e "END { print \"$SENTINEL\"; emit_ramp_shapes() }" > "$all"

  sed "/^$SENTINEL\$/,\$d" "$all" > "$body"
  sed -n "/^$SENTINEL\$/,\$p" "$all" | tail -n +2 > "$subs"

  mats=$(grep -o 'ExtResource("Mat_[A-Za-z0-9_]*")' "$body" \
         | sed 's/ExtResource("//;s/")//' | sort -u)
  steps=$(printf '%s\n' "$mats" | grep -c . || true)

  {
    printf '[gd_scene load_steps=%d format=3]\n\n' "$((steps + 2))"
    printf '; %s -- generated by tools/gen_steps.sh. Do not hand-edit.\n' "$root"
    printf '; Coordinates are MANSION-LOCAL; read the header of that script.\n\n'
    for m in $mats; do
      printf '[ext_resource type="Material" path="res://Materials/%s.tres" id="%s"]\n' "$m" "$m"
    done
    printf '\n'
    cat "$subs"
    printf '[node name="%s" type="Node3D"]\n' "$root"
    cat "$body"
  } > "$out"

  rm -f "$all" "$body" "$subs"
  printf 'wrote %s  (%s nodes)\n' "$out" "$(grep -c '^\[node' "$out")"
}

# ---------------------------------------------------------------- the stoop
#
# Three risers of 100 mm over a 900 mm run: shallow, because 300 mm is all the
# height there is and a two-step stoop reads as a kerb. 6 m wide between
# 400 mm brick cheeks, centred on the front door.
emit Scenes/steps_porch.tscn PorchSteps '
BEGIN {
  masonry_flight(".", 0, 6.0, 4.00, 0.00, 4.90, -0.30, 3,
                 "Mat_stone", "Mat_brick", 0.40, "Ramp")
}'

# -------------------------------------------------------- the cellar flight
#
# Laid on the endpoints of the existing CellarPit/Ramp: top at the inner face
# of the pit back wall, bottom where that ramp meets the pit floor. Fifteen
# risers of 220 mm -- steep, as cellar steps are, and steep is also what the
# ramp already is at 39 degrees. No cheeks: the pit walls are the cheeks.
#
# NO COLLIDER. CellarPit/Ramp in mansion.tscn is the walking surface here and
# always was -- that is the whole complaint these steps answer: collision with
# nothing to see. The endpoints below are the ones that ramp was built from,
# so the treads land exactly under its plane.
emit Scenes/steps_cellar.tscn CellarSteps '
BEGIN {
  masonry_flight(".", -10, 3.60, -41.20, -0.30, -37.20, -3.60, 15,
                 "Mat_stone", "Mat_brick", 0, "")
  # One rail, on the west side, clear of the leaf that falls that way.
  rake_pipe(".", -11.72, -41.20, -0.30, -37.20, -3.60)
}'

# CSG is how this is described, not how it should ship.
if [ -n "${GODOT:-}" ]; then
  for s in Scenes/steps_porch.tscn Scenes/steps_cellar.tscn; do
    BAKE_ONLY="res://$s" "$GODOT" --headless --path . --script tools/bake.gd \
      2>&1 | grep -E "mesh\(es\)|baked" || true
  done
else
  echo "gen_steps.sh: set GODOT= to bake; leaving live CSG for now." >&2
fi
