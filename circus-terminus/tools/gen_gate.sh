#!/usr/bin/env bash
# Writes Scenes/gate_leaf.tscn (the ironwork) and Scenes/Gate.tscn (the leaf
# hung on a hinge, with Door.gd on it so it swings and can be interacted with).
#
# Gate.tscn keeps its uid and its Hinge/Panel layout: demo_level.tscn instances
# it twice with per-instance open_angle and swing_time, and Door.gd reaches for
# $Hinge by name. Only what hangs off the Panel has changed -- it was a single
# 8x5.4 metre box, which from the road read as a garage door.
#
# The leaf is a CSGCombiner3D, deliberately. A combiner renders as one mesh, so
# a hundred and fifty bars cost one draw call, and CSG evaluates once at load.
# There is nothing for the bake pipeline to improve on and it stays editable.

set -euo pipefail
cd "$(dirname "$0")/.."

AWK=${AWK:-awk}
BODY=$(mktemp)
trap 'rm -f "$BODY"' EXIT

"$AWK" -f tools/lib.awk -f tools/items.awk -f tools/gate.awk \
  -e 'BEGIN { g_leaf() }' > "$BODY"

mats=$(grep -o 'ExtResource("Mat_[A-Za-z0-9_]*")' "$BODY" \
       | sed 's/ExtResource("//;s/")//' | sort -u)
steps=$(printf '%s\n' "$mats" | grep -c . || true)

{
  echo "[gd_scene load_steps=$((steps + 1)) format=3 uid=\"uid://cgateleaf001\"]"
  echo
  echo "; ONE GATE LEAF. Generated by tools/gen_gate.sh -- do not hand-edit."
  echo "; Built in hinge space: x 0 at the pivot, x 8.05 at the meeting stile."
  echo
  for m in $mats; do
    echo "[ext_resource type=\"Material\" path=\"res://Materials/$m.tres\" id=\"$m\"]"
  done
  echo
  echo '[node name="GateLeaf" type="CSGCombiner3D"]'
  cat "$BODY"
} > Scenes/gate_leaf.tscn

# ---- the gate itself ------------------------------------------------------
# The Panel collider stays a single box: a trimesh of the ironwork would let
# the player walk between the bars, and every gate in every game is a slab as
# far as physics is concerned.
#
# Leaf sits at Panel-local (-0.45, -1.05, 0) so that leaf-space (0,0,0) is
# hinge-space (0,0,0) -- the same place the old box's lower hinge corner was.
cat > Scenes/Gate.tscn <<'EOF'
[gd_scene load_steps=4 format=3 uid="uid://dd1vcawy0e17e"]

; THE ESTATE GATE. Generated by tools/gen_gate.sh -- do not hand-edit.
;
; demo_level.tscn instances this twice, mirrored, as Gate and Gate2, and
; overrides open_angle and swing_time on each. Door.gd drives it, so it also
; answers to Interact and can be locked like any other door.

[ext_resource type="Script" path="res://Scripts/Door.gd" id="1_door"]
[ext_resource type="PackedScene" path="res://Scenes/gate_leaf.tscn" id="2_leaf"]

[sub_resource type="BoxShape3D" id="Shape_leaf"]
size = Vector3(8.05, 5.41, 0.16)

[node name="Gate" type="Node3D" unique_id=1282124821 groups=["interactable"]]
script = ExtResource("1_door")
open_angle = 25.0
swing_time = 7.0
prompt = "The gate"

[node name="Hinge" type="Node3D" parent="."]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, -0.004639387, 0, 0)

[node name="Panel" type="AnimatableBody3D" parent="Hinge"]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0.45, 1.05, 0)
sync_to_physics = false

[node name="CollisionShape3D" type="CollisionShape3D" parent="Hinge/Panel"]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 3.575, 1.655, 0)
shape = SubResource("Shape_leaf")

[node name="Leaf" parent="Hinge/Panel" instance=ExtResource("2_leaf")]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, -0.45, -1.05, 0)
EOF

printf 'wrote Scenes/gate_leaf.tscn (%s brushes) and Scenes/Gate.tscn\n' \
  "$(grep -c '^\[node' Scenes/gate_leaf.tscn)"
