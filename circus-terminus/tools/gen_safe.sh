material_override = ExtResource("6_ash")
mesh = SubResource("Mesh_recess")

[node name="HingeBarrelLow" type="MeshInstance3D" parent="Body"]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, -0.4, -0.28, 0.3)
material_override = ExtResource("3_iron")
mesh = SubResource("Mesh_barrel")

[node name="HingeBarrelHigh" type="MeshInstance3D" parent="Body"]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, -0.4, 0.28, 0.3)
material_override = ExtResource("3_iron")
mesh = SubResource("Mesh_barrel")

[node name="FootA" type="MeshInstance3D" parent="Body"]
