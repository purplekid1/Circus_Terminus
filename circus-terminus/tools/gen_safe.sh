[sub_resource type="BoxShape3D" id="Shape_body"]
size = Vector3(0.84, 0.94, 0.62)

[sub_resource type="BoxMesh" id="Mesh_carcass"]
size = Vector3(0.84, 0.94, 0.62)

[sub_resource type="BoxMesh" id="Mesh_recess"]
