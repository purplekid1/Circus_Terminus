  n = 0
  for (sx = -1; sx <= 1; sx += 2)
    for (sy = -1; sy <= 1; sy += 2) {
      n++
      printf "\n[node name=\"Rivet%d\" type=\"MeshInstance3D\" parent=\"DoorPivot/Leaf\"]\n", n
      printf "transform = Transform3D(1, 0, 0, 0, -4.371139e-08, -1, 0, 1, -4.371139e-08, %.3f, %.3f, 0.09)\n",
             sx * 0.335, sy * 0.385
      printf "material_override = ExtResource(\"5_brass\")\n"
      printf "mesh = SubResource(\"Mesh_rivet\")\n"
    }
}'

# the handwheel: hub, five spokes, twelve rim segments
cat <<'WHEEL'

[node name="Wheel" type="Node3D" parent="DoorPivot/Leaf"]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0.245, -0.245, 0.105)

[node name="Hub" type="MeshInstance3D" parent="DoorPivot/Leaf/Wheel"]
