awk '
BEGIN {
  pi = 3.14159265358979
  spokes = 5; rim = 12; r = 0.115
  for (i = 0; i < spokes; i++) {
    a = 2 * pi * i / spokes
    c = cos(a); s = sin(a)
    # roll about Z so the spoke lies along its own radius
    printf "\n[node name=\"Spoke%d\" type=\"MeshInstance3D\" parent=\"DoorPivot/Leaf/Wheel\"]\n", i
    printf "transform = Transform3D(%.6f, %.6f, 0, %.6f, %.6f, 0, 0, 0, 1, %.5f, %.5f, 0)\n",
           c, s, -s, c, sin(a) * r * 0.5, cos(a) * r * 0.5
    printf "material_override = ExtResource(\"3_iron\")\n"
    printf "mesh = SubResource(\"Mesh_spoke\")\n"
  }
  for (i = 0; i < rim; i++) {
    a = 2 * pi * i / rim
    c = cos(a); s = sin(a)
    printf "\n[node name=\"Rim%d\" type=\"MeshInstance3D\" parent=\"DoorPivot/Leaf/Wheel\"]\n", i
    printf "transform = Transform3D(%.6f, %.6f, 0, %.6f, %.6f, 0, 0, 0, 1, %.5f, %.5f, 0)\n",
           c, s, -s, c, sin(a) * r, cos(a) * r
    printf "material_override = ExtResource(\"3_iron\")\n"
    printf "mesh = SubResource(\"Mesh_rimseg\")\n"
  }
}'

