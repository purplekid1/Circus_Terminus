# placed in the world by parts/props.part at a transform tuned to where its
# face lands in the office wall, and moving the origin here would push it
# through the plaster.
#
#   DoorPivot   safe-local (-0.39, 0.47, 0.31) -- the hinge line
#     Leaf      the swinging plate, at the centre of the front face
#     Dials     three instances of safe_dial.tscn, 0.22 apart
