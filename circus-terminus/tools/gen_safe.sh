;
; The handwheel rim is a ring of short boxes rather than a torus mesh, which
; is the same trick the dial knurling uses: Godot has no torus primitive in
; the .tscn sub-resource set worth using here, and twelve boxes round a circle
; read as a cast-iron wheel at the distance the focus camera sits at.

[ext_resource type="Script" path="res://Scripts/Safe.gd" id="1_safe"]
[ext_resource type="PackedScene" path="res://Scenes/safe_dial.tscn" id="2_dial"]
[ext_resource type="Material" path="res://Materials/Mat_iron.tres" id="3_iron"]
