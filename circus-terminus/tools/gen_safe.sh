#!/usr/bin/env bash
# Writes Scenes/safe_dial.tscn -- one combination dial, instanced three times
# by Scenes/safe.tscn.
#
# Generated rather than hand-written for one reason: a dial that reads as a
# dial needs a knurled rim and ten engraved graduations, which is thirty-odd
# little boxes placed round a circle. That is a loop, not something to type out
# and then get wrong when the radius changes.
#
# THE SPIN NODE IS THE WHOLE POINT OF THE NODE LAYOUT.
#
# The dial used to be a pitched cylinder that Safe.gd spun by setting
# `rotation.z`. Godot composes Euler angles as Ry*Rx*Rz, so with the pitch
# already on X, a Z angle rotates about the cylinder's own SIDEWAYS axis --
# it tumbled the disc end over end like a flipping coin instead of turning it
# in its own plane.
#
# Neither Euler channel does the right thing once a pitch is present, so the
# pitch lives on `Spin` and `Ring` is left square. Ring's local Y is then
# exactly the cylinder's axis, and `Ring.rotation.y` is a true dial turn.
#
# Under Spin (pitched -90 about X) a child at local (x, y, z) lands at world
# (x, z, -y): local Y runs INTO the door, local XZ is the face of the dial.

set -euo pipefail
cd "$(dirname "$0")/.."

OUT=Scenes/safe_dial.tscn

R_BEZEL=0.100
R_RING=0.085
R_KNURL=0.086
R_TICK=0.066
KNURLS=20
TICKS=10

{
cat <<'HEAD'
[gd_scene load_steps=8 format=3 uid="uid://c8qkx1vn7safe"]

; ONE COMBINATION DIAL. Generated by tools/gen_safe.sh -- do not hand-edit.
;
; Dial
;   Bezel     brass surround, fixed to the door
;   Spin      carries the -90 pitch. NEVER rotate this from script.
;     Ring    the disc itself; Safe.gd turns THIS, about its own local Y
;       Knurl / Grad   rim grip and graduations, so the turn is visible
;   Pointer   the index mark the number is read against, fixed
;   Digit     the current number, fixed and upright

[ext_resource type="Material" path="res://Materials/Mat_brass.tres" id="1_brass"]
[ext_resource type="Material" path="res://Materials/Mat_steel.tres" id="2_steel"]
[ext_resource type="Material" path="res://Materials/Mat_iron.tres" id="3_iron"]

[sub_resource type="CylinderMesh" id="Mesh_bezel"]
top_radius = 0.1
bottom_radius = 0.106
height = 0.016
radial_segments = 28

[sub_resource type="CylinderMesh" id="Mesh_ring"]
top_radius = 0.085
bottom_radius = 0.085
height = 0.03
radial_segments = 28

[sub_resource type="CylinderMesh" id="Mesh_cap"]
top_radius = 0.028
bottom_radius = 0.028
height = 0.038
radial_segments = 16

[sub_resource type="BoxMesh" id="Mesh_knurl"]
size = Vector3(0.008, 0.028, 0.012)

[sub_resource type="BoxMesh" id="Mesh_grad"]
size = Vector3(0.004, 0.006, 0.018)

[sub_resource type="BoxMesh" id="Mesh_index"]
size = Vector3(0.006, 0.03, 0.022)

[sub_resource type="BoxMesh" id="Mesh_pointer"]
size = Vector3(0.012, 0.026, 0.008)

[node name="Dial" type="Node3D"]

[node name="Bezel" type="MeshInstance3D" parent="."]
transform = Transform3D(1, 0, 0, 0, -4.371139e-08, -1, 0, 1, -4.371139e-08, 0, 0, 0.004)
material_override = ExtResource("1_brass")
mesh = SubResource("Mesh_bezel")

[node name="Spin" type="Node3D" parent="."]
transform = Transform3D(1, 0, 0, 0, -4.371139e-08, -1, 0, 1, -4.371139e-08, 0, 0, 0.018)

[node name="Ring" type="MeshInstance3D" parent="Spin"]
material_override = ExtResource("2_steel")
mesh = SubResource("Mesh_ring")

[node name="Cap" type="MeshInstance3D" parent="Spin/Ring"]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, -0.012, 0)
material_override = ExtResource("1_brass")
mesh = SubResource("Mesh_cap")

[node name="Index" type="MeshInstance3D" parent="Spin/Ring"]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, -0.008, 0.064)
material_override = ExtResource("1_brass")
mesh = SubResource("Mesh_index")
HEAD

# Knurling round the rim, and graduations on the face. Both are children of
# Ring, so both turn with it -- which is the only reason the player can see
# that the dial has moved at all between two adjacent digits.
awk -v n="$KNURLS" -v r="$R_KNURL" '
BEGIN {
  pi = 3.14159265358979
  for (i = 0; i < n; i++) {
    a = 2 * pi * i / n
    c = cos(a); s = sin(a)
    printf "\n[node name=\"Knurl%d\" type=\"MeshInstance3D\" parent=\"Spin/Ring\"]\n", i
    # rotation about local Y so each grip faces out of the rim
    printf "transform = Transform3D(%.6f, 0, %.6f, 0, 1, 0, %.6f, 0, %.6f, %.5f, 0, %.5f)\n",
           c, s, -s, c, r * s, r * c
    printf "material_override = ExtResource(\"3_iron\")\n"
    printf "mesh = SubResource(\"Mesh_knurl\")\n"
  }
}'

awk -v n="$TICKS" -v r="$R_TICK" '
BEGIN {
  pi = 3.14159265358979
  for (i = 0; i < n; i++) {
    a = 2 * pi * i / n
    c = cos(a); s = sin(a)
    printf "\n[node name=\"Grad%d\" type=\"MeshInstance3D\" parent=\"Spin/Ring\"]\n", i
    printf "transform = Transform3D(%.6f, 0, %.6f, 0, 1, 0, %.6f, 0, %.6f, %.5f, -0.016, %.5f)\n",
           c, s, -s, c, r * s, r * c
    printf "material_override = ExtResource(\"1_brass\")\n"
    printf "mesh = SubResource(\"Mesh_grad\")\n"
  }
}'

cat <<'TAIL'

[node name="Pointer" type="MeshInstance3D" parent="."]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0.113, 0.026)
material_override = ExtResource("1_brass")
mesh = SubResource("Mesh_pointer")

[node name="Digit" type="Label3D" parent="."]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, -0.155, 0.03)
pixel_size = 0.0022
text = "0"
font_size = 72
outline_size = 18
TAIL
} > "$OUT"

printf 'wrote %s  (%s nodes)\n' "$OUT" "$(grep -c '^\[node' "$OUT")"


# ===========================================================================
