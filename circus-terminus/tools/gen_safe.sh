[sub_resource type="BoxMesh" id="Mesh_foot"]
size = Vector3(0.1, 0.05, 0.1)

[sub_resource type="CylinderMesh" id="Mesh_rivet"]
top_radius = 0.016
bottom_radius = 0.016
height = 0.014
radial_segments = 10

[sub_resource type="CylinderMesh" id="Mesh_barrel"]
top_radius = 0.026
bottom_radius = 0.026
height = 0.12
radial_segments = 12

[sub_resource type="CylinderMesh" id="Mesh_hub"]
top_radius = 0.038
bottom_radius = 0.038
height = 0.07
radial_segments = 16

[sub_resource type="BoxMesh" id="Mesh_spoke"]
size = Vector3(0.018, 0.1, 0.026)

[sub_resource type="BoxMesh" id="Mesh_rimseg"]
size = Vector3(0.062, 0.026, 0.026)

[node name="Safe" type="Node3D" groups=["interactable"]]
script = ExtResource("1_safe")
prompt = "Work the dials"

[node name="Body" type="StaticBody3D" parent="."]
transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0.47, 0)

[node name="CollisionShape3D" type="CollisionShape3D" parent="Body"]
shape = SubResource("Shape_body")

[node name="Carcass" type="MeshInstance3D" parent="Body"]
material_override = ExtResource("3_iron")
