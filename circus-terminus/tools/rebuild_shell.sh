#!/usr/bin/env bash
# Rebuilds ONLY the building's shell and exterior meshes, in place.
#
#   GODOT=/path/to/godot tools/rebuild_shell.sh
#
# Once mansion.tscn has been arranged by hand, build.sh is off the table --
# it would rewrite the whole scene and throw the layout away. But the shell
# (walls, floors, gables) and the exterior (roof, porch, trim) are each a
# single baked mesh hanging off a single node:
#
#   Shell     -> Meshes/mansion_Shell.res     + mansion_Shell_col.res
#   Exterior  -> Meshes/mansion_Exterior.res  + mansion_Exterior_col.res
#
# So the building itself can be regenerated by rewriting those four files.
# mansion.tscn is not touched at all: it still points at the same paths, and
# every piece of furniture in it stays exactly where it was put.
#
# This is the route for anything structural -- a wall moved, a window added,
# the roof pitch changed. Use build.sh only if you mean to start the layout
# over.

set -euo pipefail
cd "$(dirname "$0")/.."

AWK=${AWK:-awk}
TMP_SCENE=Scenes/_shell_rebuild.tscn
trap 'rm -f "$TMP_SCENE"' EXIT

if [ -z "${GODOT:-}" ]; then
  for c in godot godot4 Godot; do
    if command -v "$c" >/dev/null 2>&1; then GODOT=$c; break; fi
  done
fi
if [ -z "${GODOT:-}" ]; then
  echo "rebuild_shell.sh: no Godot binary found. Set GODOT=/path/to/godot." >&2
  exit 1
fi

# The two combiners, and nothing else, in a scene of their own.
NODES=$(mktemp); trap 'rm -f "$TMP_SCENE" "$NODES"' EXIT
{
  bash tools/gen_shell.sh
  echo
  bash tools/gen_exterior.sh
} > "$NODES"

# Declare exactly the materials they reference, the same way gen_header.sh
# does, so the editor cannot prune one out from under us.
{
  echo '[gd_scene format=3]'
  echo
  grep -o 'ExtResource("Mat_[A-Za-z0-9_]*")' "$NODES" \
    | sed 's/ExtResource("//;s/")//' | sort -u \
    | while read -r m; do
        echo "[ext_resource type=\"Material\" path=\"res://Materials/$m.tres\" id=\"$m\"]"
      done
  echo
  echo '[node name="Building" type="Node3D"]'
  cat "$NODES"
} > "$TMP_SCENE"

"$GODOT" --headless --path . --script tools/rebuild_shell.gd

# Strip uids off every Meshes/ reference in the scene.
#
# This bake writes new .res files, and Godot hands a rewritten resource a NEW
# uid. Any uid sitting in mansion.tscn is therefore stale the moment this runs,
# and Godot warns "invalid UID ... using text path instead" once per reference
# on every load -- four warnings after this script, and fifty-four once the
# rest of the meshes are rebaked.
#
# The scene does not normally carry them: gen_header.sh emits paths only, for
# exactly this reason. But the EDITOR writes them back in every time somebody
# saves mansion.tscn from inside Godot, so this has to run after each bake
# rather than being fixed once.
sed -i -E '/ext_resource.*res:\/\/Meshes\//s/ uid="uid:\/\/[^"]*"//' Scenes/mansion.tscn

printf 'rebuilt Meshes/mansion_{Shell,Exterior}{,_col}.res\n'
